#!/usr/bin/env node
// Renders every spoken line in js/script.js with macOS `say`, one voice per character.
// Writes audio/voices/<scene>-<n>.m4a and audio/voices/index.js (F.VOICE_LINES).
// A line that would run into the next one is re-rendered faster, up to MAX_SPEEDUP.
// Usage: node tools/build-voices.mjs            (macOS only; free, offline)
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const OUT = path.join(ROOT, 'audio', 'voices');

// voice, words per minute
export const CAST = {
  narrator: ['Daniel', 175],
  magic: ['Samantha', 150],
  dry: ['Fred', 165],
  official: ['Eddy (English (US))', 185],
  state: ['Reed (English (US))', 175],
  engineer: ['Grandpa (English (US))', 190],
  consultant: ['Rocko (English (US))', 185],
  comm1: ['Shelley (English (US))', 180],
  comm2: ['Sandy (English (US))', 180],
  clerk: ['Kathy', 185],
  member: ['Flo (English (US))', 180],
  citizen: ['Sandy (English (UK))', 180],
  captain: ['Rocko (English (UK))', 175],
  meter: ['Zarvox', 170],
  windsurfer: ['Eddy (English (UK))', 185],
};
const MAX_SPEEDUP = 1.3;
const GAP = 0.15; // breathing room before the next line

const ctx = { window: {}, console };
ctx.F = ctx.window.F = {};
vm.createContext(ctx);
for (const f of ['js/core.js', 'js/script.js']) vm.runInContext(fs.readFileSync(path.join(ROOT, f), 'utf8'), ctx, { filename: f });
const F = ctx.F;

const speakable = (t) => t.replace(/…/g, '...').replace(/—/g, ', ').replace(/\s+/g, ' ').trim();
const duration = (file) => {
  const m = execFileSync('afinfo', [file], { encoding: 'utf8' }).match(/estimated duration: ([\d.]+)/);
  return m ? +m[1] : 0;
};
const render = (file, voice, rate, text) =>
  execFileSync('say', ['-v', voice, '-r', String(Math.round(rate)), '--file-format=m4af', '--data-format=aac', '--bit-rate=48000', '-o', file, text]);

fs.mkdirSync(OUT, { recursive: true });
const lines = {};
const report = [];
for (const scene of F.SCRIPT) {
  const spoken = scene.cues.filter((c) => c.kind !== 'sfx' && c.text);
  spoken.forEach((c, i) => {
    const who = c.who || c.kind;
    const [voice, wpm] = CAST[who] || CAST.narrator;
    const next = spoken[i + 1];
    const slot = (next ? next.at : scene.dur) - c.at - GAP;
    const name = `${scene.id}-${String(i + 1).padStart(2, '0')}.m4a`;
    const file = path.join(OUT, name);
    const text = speakable(c.text);
    let rate = wpm;
    render(file, voice, rate, text);
    let dur = duration(file);
    if (dur > slot) {
      rate = wpm * Math.min(MAX_SPEEDUP, (dur / slot) * 1.03);
      render(file, voice, rate, text);
      dur = duration(file);
    }
    const key = scene.id + ':' + scene.cues.indexOf(c);
    lines[key] = { src: 'audio/voices/' + name, dur: +dur.toFixed(2) };
    report.push({ scene: scene.id, at: c.at, who, voice, rate: Math.round(rate), dur, slot, over: dur > slot ? +(dur - slot).toFixed(2) : 0, text: c.text });
  });
}
fs.writeFileSync(
  path.join(OUT, 'index.js'),
  "'use strict';\n// Generated by tools/build-voices.mjs: one clip per spoken cue, keyed by scene id and cue index.\nF.VOICE_LINES = " + JSON.stringify(lines, null, 1) + ';\nF.VOICE_CAST = ' + JSON.stringify(CAST) + ';\n',
);
fs.writeFileSync(path.join(OUT, 'report.json'), JSON.stringify(report, null, 1));
const over = report.filter((r) => r.over);
console.log(report.length + ' lines rendered; ' + over.length + ' still run long:');
over.forEach((r) => console.log(`  ${r.scene} @${r.at}s ${r.who} +${r.over}s  ${r.text}`));
